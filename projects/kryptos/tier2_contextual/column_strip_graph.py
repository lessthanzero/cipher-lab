"""Tier 2 Column Strip Graph Engine for Kryptos K4.

Analyzes the 14x7 column strip structure under physical cipher mechanics:
1. Graph Formulation:
   Constructs transition graphs G_c = (V, E) for each column c in 0..6 across:
   - Row 3 -> Row 4 (delta r = 1)
   - Row 9 -> Row 10 (delta r = 1)
   - Row 4 -> Row 9 (delta r = 5)
   - Row 10 -> Row 3 mod 14 (delta r = 7)

2. Master Strip Alignment Solver:
   Tests whether column keystreams K[r, c] can be generated by:
   - A single master alphabet strip Sigma = (s_0, s_1, ..., s_25)
   - Shift parameters beta_c in [0..25] and advance rates alpha_c in [0..25]:
       K[r, c] == Sigma[(alpha_c * r + beta_c) mod 26]
   - Constrained to known classical strips (Standard, Kryptos, Palimpsest, Abscissa).

3. Exact Consistency Checks across all 4 cipher variants:
   - Standard Vigenere
   - Kryptos Vigenere
   - Standard Beaufort
   - Kryptos Beaufort
"""


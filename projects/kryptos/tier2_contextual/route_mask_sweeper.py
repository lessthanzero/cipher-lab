GRID_ROWS = 14
GRID_COLS = 7
GRID_CELLS = 98
TEXT_LEN = 97


def get_standard_routes() -> Dict[str, List[int]]:
    """
    Generate standard 14x7 planar route permutations of length 97.
    A permutation pi maps linear index i in [0..96] to cell index pi(i).
    The 98th unused cell is placed at (13, 6) by default.
    """
    routes: Dict[str, List[int]] = {}

    # Valid grid cells in row-major: (r, c) -> r * 7 + c for r in 0..13, c in 0..6
    valid_cells = [(r, c) for r in range(GRID_ROWS) for c in range(GRID_COLS) if (r * GRID_COLS + c) < TEXT_LEN]

    # 1. Row-major Left-to-Right (identity)
    routes["row_lr"] = list(range(TEXT_LEN))

    # 2. Row-major Right-to-Left
    rl = []
    for r in range(GRID_ROWS):
        for c in reversed(range(GRID_COLS)):
            idx = r * GRID_COLS + c
            if idx < TEXT_LEN:
                rl.append(idx)
    routes["row_rl"] = rl

    # 3. Row Boustrophedon (even L->R, odd R->L)
    boust_r = []
    for r in range(GRID_ROWS):
        cols = range(GRID_COLS) if r % 2 == 0 else reversed(range(GRID_COLS))
        for c in cols:
            idx = r * GRID_COLS + c
            if idx < TEXT_LEN:
                boust_r.append(idx)
    routes["boustrophedon_row"] = boust_r

    # 4. Row Boustrophedon (odd L->R, even R->L)
    boust_r_inv = []
    for r in range(GRID_ROWS):
        cols = reversed(range(GRID_COLS)) if r % 2 == 0 else range(GRID_COLS)
        for c in cols:
            idx = r * GRID_COLS + c
            if idx < TEXT_LEN:
                boust_r_inv.append(idx)
    routes["boustrophedon_row_alt"] = boust_r_inv

    # 5. Column-major Top-to-Bottom
    col_tb = []
    for c in range(GRID_COLS):
        for r in range(GRID_ROWS):
            idx = r * GRID_COLS + c
            if idx < TEXT_LEN:
                col_tb.append(idx)
    routes["col_tb"] = col_tb

    # 6. Column-major Bottom-to-Top (Sanborn K3 style)
    col_bt = []
    for c in range(GRID_COLS):
        for r in reversed(range(GRID_ROWS)):
            idx = r * GRID_COLS + c
            if idx < TEXT_LEN:
                col_bt.append(idx)
    routes["col_bt"] = col_bt

    # 7. Column Boustrophedon (even T->B, odd B->T)
    boust_c = []
    for c in range(GRID_COLS):
        rows = range(GRID_ROWS) if c % 2 == 0 else reversed(range(GRID_ROWS))
        for r in rows:
            idx = r * GRID_COLS + c
            if idx < TEXT_LEN:
                boust_c.append(idx)
    routes["boustrophedon_col"] = boust_c

    # 8. Column Boustrophedon (odd T->B, even B->T)
    boust_c_inv = []
    for c in range(GRID_COLS):
        rows = reversed(range(GRID_ROWS)) if c % 2 == 0 else range(GRID_ROWS)
        for r in rows:
            idx = r * GRID_COLS + c
            if idx < TEXT_LEN:
                boust_c_inv.append(idx)
    routes["boustrophedon_col_alt"] = boust_c_inv

    # 9. Diagonals (Top-Left to Bottom-Right)
    diag_tl = []
    for diag in range(GRID_ROWS + GRID_COLS - 1):
        for r in range(GRID_ROWS):
            c = diag - r
            if 0 <= c < GRID_COLS:
                idx = r * GRID_COLS + c
                if idx < TEXT_LEN:
                    diag_tl.append(idx)
    routes["diagonal_tl_br"] = diag_tl

    # 10. Diagonals (Top-Right to Bottom-Left)
    diag_tr = []
    for diag in range(GRID_ROWS + GRID_COLS - 1):
        for r in range(GRID_ROWS):
            c = GRID_COLS - 1 - (diag - r)
            if 0 <= c < GRID_COLS:
                idx = r * GRID_COLS + c
                if idx < TEXT_LEN:
                    diag_tr.append(idx)
    routes["diagonal_tr_bl"] = diag_tr

    return routes


def test_route_period_consistency(
    pi: List[int],
    period: int,
    anchor_keys: Dict[int, int],
) -> Tuple[bool, int, int]:
    """
    Test if route permutation pi is consistent with periodic key of length `period`.
    anchor_keys maps linear text index i to required key value (0..25).
    Returns (is_consistent, num_tested_residues, num_conflicts).
    """
    residues: Dict[int, int] = {}
    conflicts = 0

    for idx, req_k in anchor_keys.items():
        if idx >= len(pi):
            continue
        mapped_pos = pi[idx]
        rem = mapped_pos % period
        if rem in residues:
            if residues[rem] != req_k:
                conflicts += 1
        else:
            residues[rem] = req_k

    return (conflicts == 0), len(residues), conflicts


def sweep_columnar_permutations(
    anchor_keys: Dict[int, int],
    alphabet_name: str,
    max_period: int = 14,
) -> List[Dict[str, Any]]:
    """
    Exhaustively evaluate all 7! = 5,040 column permutations of the 14x7 grid.
    For each permutation, tests reading top-to-bottom and bottom-to-top across periods 1..max_period.
    """
    hits = []
    cols = list(range(GRID_COLS))

    for col_order in itertools.permutations(cols):
        # 1. Top to bottom
        pi_tb = []
        for c in col_order:
            for r in range(GRID_ROWS):
                idx = r * GRID_COLS + c
                if idx < TEXT_LEN:
                    pi_tb.append(idx)

        # 2. Bottom to top (K3 style)
        pi_bt = []
        for c in col_order:
            for r in reversed(range(GRID_ROWS)):
                idx = r * GRID_COLS + c
                if idx < TEXT_LEN:
                    pi_bt.append(idx)

        for mode_name, pi in [("top_to_bottom", pi_tb), ("bottom_to_top", pi_bt)]:
            # Invert permutation so pi_inv[linear_idx] gives position in readout
            pi_inv = [0] * TEXT_LEN
            for readout_pos, linear_idx in enumerate(pi):
                if linear_idx < TEXT_LEN:
                    pi_inv[linear_idx] = readout_pos

            for p in range(1, max_period + 1):
                ok, n_res, confs = test_route_period_consistency(pi_inv, p, anchor_keys)
                # If zero conflicts and tested at least 5 residues
                if ok and n_res >= 5:
                    hits.append({
                        "col_order": list(col_order),
                        "read_direction": mode_name,
                        "period": p,
                        "tested_residues": n_res,
                        "conflicts": confs,
                        "alphabet": alphabet_name,
                    })

    return hits


def run_route_sweep_campaign() -> Dict[str, Any]:
    """Execute complete route transposition sweep on standard routes and column permutations."""
    pairs = extract_known_pairs()

    # Precalculate required keys under Kryptos Vigenere and Standard Vigenere
    anchor_keys_kry = {
        idx: (KRYPTOS_ALPHABET.index(c) - KRYPTOS_ALPHABET.index(p)) % 26
        for idx, c, p in pairs
    }
    anchor_keys_std = {
        idx: (STANDARD_ALPHABET.index(c) - STANDARD_ALPHABET.index(p)) % 26
        for idx, c, p in pairs
    }

    results: Dict[str, Any] = {
        "standard_routes": {},
        "columnar_permutation_hits": [],
    }

    # 1. Sweep standard geometric routes
    std_routes = get_standard_routes()
    for route_name, route_pi in std_routes.items():
        # Invert to map linear index -> route readout position
        pi_inv = [0] * TEXT_LEN
        for pos, lin_idx in enumerate(route_pi):
            if lin_idx < TEXT_LEN:
                pi_inv[lin_idx] = pos

        route_rep = {}
        for p in range(1, 15):
            ok_kry, n_kry, c_kry = test_route_period_consistency(pi_inv, p, anchor_keys_kry)
            ok_std, n_std, c_std = test_route_period_consistency(pi_inv, p, anchor_keys_std)
            route_rep[f"period_{p}"] = {
                "kryptos_conflicts": c_kry,
                "standard_conflicts": c_std,
                "kryptos_consistent": ok_kry,
                "standard_consistent": ok_std,
            }
        results["standard_routes"][route_name] = route_rep

    # 2. Sweep all 5,040 column permutations on Kryptos tableau
    t0 = time.time()
    col_hits_kry = sweep_columnar_permutations(anchor_keys_kry, "KRYPTOS", max_period=14)
    col_hits_std = sweep_columnar_permutations(anchor_keys_std, "STANDARD", max_period=14)
    elapsed = time.time() - t0

    results["columnar_permutation_hits"] = col_hits_kry + col_hits_std
    results["columnar_sweep_time_s"] = round(elapsed, 3)

    return results



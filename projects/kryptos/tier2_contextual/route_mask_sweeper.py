"""Tier 2 Route Transposition and Masking Sweeper for Kryptos K4.

Evaluates 14x7 geometric routes and column permutations on:
1. Model 3 (Consilium Gate 3 Consensus): Key generated by route permutation pi on periodic text T:
     K[i] = T[pi(i)], where T has period L in [1..14].
     Required: K_req[i1] == K_req[i2] whenever pi(i1) = pi(i2) mod L.
2. Model 1 (Plaintext route): C[i] = Sub(P[pi(i)], K[i]).
3. Model 2 (Ciphertext route): C[pi(i)] = Sub(P[i], K[i]).
4. Cardan Grille (Binary Mask) decomposition into dual periodic streams.

Supports execution on mac-primary and offloading to Fedora PC worker.
"""


CORPORA_PATH = Path(__file__).parent.parent.parent.parent / "data" / "corpora" / "kryptos_historical" / "kryptos_k1_k2_k3_plaintexts.txt"


def load_k1_k2_k3_plaintexts() -> Dict[str, str]:
    """Parse K1, K2, and K3 plaintexts from historical corpora file."""
    texts = {}
    if not CORPORA_PATH.exists():
        return texts

    with open(CORPORA_PATH, "r", encoding="utf-8") as f:
        content = f.read()

    # Split into sections by heading
    current_key = "UNKNOWN"
    current_lines = []

    for line in content.splitlines():
        line_s = line.strip()
        if line_s.startswith("### K1"):
            if current_lines:
                texts[current_key] = re.sub(r"[^A-Z]", "", "".join(current_lines).upper())
            current_key = "K1"
            current_lines = []
        elif line_s.startswith("### K2"):
            if current_lines:
                texts[current_key] = re.sub(r"[^A-Z]", "", "".join(current_lines).upper())
            current_key = "K2"
            current_lines = []
        elif line_s.startswith("### K3"):
            if current_lines:
                texts[current_key] = re.sub(r"[^A-Z]", "", "".join(current_lines).upper())
            current_key = "K3"
            current_lines = []
        elif not line_s.startswith("#") and line_s:
            current_lines.append(line_s)

    if current_lines:
        texts[current_key] = re.sub(r"[^A-Z]", "", "".join(current_lines).upper())

    return texts


def evaluate_cross_section_offset(
    k4_anchors: List[Tuple[int, str, str]],
    source_text: str,
    offset: int,
    alphabet: str,
    cipher_type: str = "vigenere",
    is_wrapped: bool = False,
) -> Tuple[int, int, float]:
    """
    Test how many K4 anchors match when key K[i] = source_text[offset + i].
    Returns (matches, total_tested, match_rate).
    """
    matches = 0
    total = len(k4_anchors)
    src_len = len(source_text)

    for idx, c, p in k4_anchors:
        if is_wrapped:
            src_pos = (offset + idx) % src_len
        else:
            src_pos = offset + idx
            if src_pos >= src_len or src_pos < 0:
                continue

        key_char = source_text[src_pos]
        c_val = alphabet.index(c)
        p_val = alphabet.index(p)
        k_val = alphabet.index(key_char)

        if cipher_type == "vigenere":
            exp_c = (p_val + k_val) % 26
        elif cipher_type == "beaufort":
            exp_c = (k_val - p_val) % 26
        elif cipher_type == "variant_beaufort":
            exp_c = (p_val - k_val) % 26
        else:
            exp_c = (p_val + k_val) % 26

        if exp_c == c_val:
            matches += 1

    return matches, total, matches / total


def sweep_cross_section_layers() -> Dict[str, Any]:
    """Sweep all offsets across K1, K2, and K3 plaintexts for Layer Two coupling."""
    sections = load_k1_k2_k3_plaintexts()
    anchors = extract_known_pairs()

    report: Dict[str, Any] = {}
    alphabets = [("KRYPTOS", KRYPTOS_ALPHABET), ("STANDARD", STANDARD_ALPHABET)]
    cipher_types = ["vigenere", "beaufort", "variant_beaufort"]

    for sec_name, text in sections.items():
        sec_results = []
        max_offset = len(text) if len(text) < 97 else len(text) - 24

        for alph_name, alph in alphabets:
            for c_type in cipher_types:
                for off in range(len(text)):
                    # Wrapped mode
                    m, t, r = evaluate_cross_section_offset(
                        k4_anchors=anchors,
                        source_text=text,
                        offset=off,
                        alphabet=alph,
                        cipher_type=c_type,
                        is_wrapped=True,
                    )
                    if r >= 0.25:  # >= 6/24 matches
                        sec_results.append({
                            "section": sec_name,
                            "offset": off,
                            "alphabet": alph_name,
                            "cipher_type": c_type,
                            "matches": m,
                            "total": t,
                            "match_rate": round(r, 4),
                        })

        sec_results.sort(key=lambda x: x["match_rate"], reverse=True)
        report[sec_name] = {
            "text_length": len(text),
            "total_hits_above_25pct": len(sec_results),
            "best_hits": sec_results[:5],
        }

    return report



"""Tier 2 Cross-Section 'LAYER TWO' Coupling Engine for Kryptos K4.

Tests whether K4's keystream or ciphertext is generated by cross-section superposition
with K1, K2, or K3 plaintexts/ciphertexts (as indicated by the explicit K2 phrase 'LAYER TWO'):

Models:
1. Direct Alignment:
   K4[i] <-> K1[i], K2[i], K3[i]
2. Modulo-Shifted Alignment:
   K4[i] <-> K1[(offset + i) % len(K1)]
   K4[i] <-> K2[(offset + i) % len(K2)]
   K4[i] <-> K3[(offset + i) % len(K3)]
3. 14-Wide Grid Superposition:
   K1 (14 cols), K2 (14 cols), K3 (14 cols, 24x14) cell-to-cell differential with K4 (14x7).
4. Physical Sculpture Screen Co-location:
   On the Kryptos sculpture, K1-K4 are on the left/right copper panels.
   Tests differential subtraction C_K4[i] - P_Kx[i] mod 26 across all 24 anchors.
"""


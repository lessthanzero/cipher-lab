"""Quagmire I, II, III, IV Dual-Keyed Slide Matrix Engine for Kryptos K4.

Evaluates the American Cryptogram Association (ACA) Quagmire cipher family
across all historical keywords under strict held-out cross-validation:

1. Cipher Mechanics:
   - Plaintext alphabet sigma_plain generated by keyword Key_P (or Standard A-Z).
   - Ciphertext alphabet sigma_cipher generated by keyword Key_C (or Standard A-Z).
   - For any alphabet pair (sigma_plain, sigma_cipher), the indicator shift at crib
     index i is uniquely determined:
     s_i = (sigma_cipher^{-1}(C_i) - sigma_plain^{-1}(P_i)) mod 26.

2. Evaluated Quagmire Types:
   - Quagmire I: Keyed plain, Standard cipher.
   - Quagmire II: Standard plain, Keyed cipher.
   - Quagmire III: Keyed plain == Keyed cipher (Kryptos tableau standard).
   - Quagmire IV: Distinct keyed plain and keyed cipher alphabets (38 x 38 pairs).

3. Indicator Models Tested:
   - Model A: Periodic Indicator (periods L in [1..14]).
     Checked for zero conflicts on Crib 1, validated on held-out Crib 2.
   - Model B: Keyword Indicator (indicator key = val(Key_Ind[i % L])).
     Sweeps all 38 historical keywords as indicators.
   - Model C: 7-Column Linear Track Indicator:
     s[r, c] = (s0[c] + r * Delta[c]) mod 26.

4. Records formal trial k4-h33 into DuckDB epistemic ledger.
"""

